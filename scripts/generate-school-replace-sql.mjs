import fs from "node:fs";
import path from "node:path";
import XLSX from "xlsx";

const cwd = process.cwd();
const inputFile = process.argv[2] || "hyd all schools.xlsx";
const outputFile = process.argv[3] || "supabase/school_list_hyd_replace.sql";

const inputPath = path.resolve(cwd, inputFile);
const outputPath = path.resolve(cwd, outputFile);

if (!fs.existsSync(inputPath)) {
  console.error(`Input file not found: ${inputPath}`);
  process.exit(1);
}

const workbook = XLSX.readFile(inputPath);
const firstSheet = workbook.SheetNames[0];
const worksheet = workbook.Sheets[firstSheet];
const rows = XLSX.utils.sheet_to_json(worksheet, { defval: "" });

const normalize = (value) =>
  String(value || "")
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, " ")
    .trim()
    .replace(/\s+/g, " ");

const cleanText = (value) => {
  const text = String(value || "").trim();
  if (!text) return "";
  if (["nan", "na", "n/a", "null", "undefined", "-"].includes(text.toLowerCase())) return "";
  return text;
};

const inferState = (address) => {
  const text = String(address || "");
  if (/telangana/i.test(text)) return "Telangana";
  if (/andhra pradesh/i.test(text)) return "Andhra Pradesh";
  if (/karnataka/i.test(text)) return "Karnataka";
  if (/tamil nadu/i.test(text)) return "Tamil Nadu";
  return "Telangana";
};

const inferInstitutionType = (category) => {
  const text = String(category || "").toLowerCase();
  if (text.includes("college")) return "College";
  return "School";
};

const inferCity = (area, address) => {
  const areaText = cleanText(area);
  if (areaText) return areaText;
  if (/hyderabad/i.test(String(address || ""))) return "Hyderabad";
  return "Hyderabad";
};

const sqlText = (value) => {
  if (value === null || value === undefined || value === "") return "''";
  return `'${String(value).replace(/'/g, "''")}'`;
};

const sqlNumeric = (value) => {
  if (value === null || value === undefined || value === "") return "null";
  const n = Number(value);
  if (!Number.isFinite(n)) return "null";
  return String(n);
};

const prepared = rows
  .map((row) => {
    const name = cleanText(row.Name);
    if (!name) return null;

    const address = cleanText(row.Address);
    const area = cleanText(row.Area);
    const phone = cleanText(row.Phone);
    const website = cleanText(row.Website);
    const institutionType = inferInstitutionType(row.Category);
    const city = inferCity(area, address);
    const state = inferState(address);
    const normalized = normalize(name);
    const latitude = row.Latitude;
    const longitude = row.Longitude;

    return {
      name,
      normalized_name: normalized,
      institution_type: institutionType,
      address_line_1: address,
      area,
      city,
      state,
      primary_contact_phone: phone,
      website,
      latitude,
      longitude,
    };
  })
  .filter(Boolean);

const dedupedMap = new Map();
for (const item of prepared) {
  const key = `${item.normalized_name}::${item.institution_type}`;
  if (!dedupedMap.has(key)) dedupedMap.set(key, item);
}
const deduped = [...dedupedMap.values()];

const valuesSql = deduped
  .map(
    (row) =>
      `  (${sqlText(row.name)},${sqlText(row.normalized_name)},${sqlText(row.institution_type)},${sqlText(
        row.address_line_1,
      )},${sqlText(row.area)},${sqlText(row.city)},${sqlText(row.state)},${sqlText(row.primary_contact_phone)},${sqlText(
        row.website,
      )},${sqlNumeric(row.latitude)},${sqlNumeric(row.longitude)})`,
  )
  .join(",\n");

const sql = `-- Replace/refresh Hyderabad institutions from Excel
-- Source: ${path.basename(inputPath)}
-- Generated by: scripts/generate-school-replace-sql.mjs
-- Rows in Excel: ${rows.length}
-- Rows after cleanup+dedupe: ${deduped.length}

begin;

with incoming(
  name,
  normalized_name,
  institution_type,
  address_line_1,
  area,
  city,
  state,
  primary_contact_phone,
  website,
  latitude,
  longitude
) as (
values
${valuesSql}
),
ins as (
  insert into public.institutions (
    name,
    normalized_name,
    institution_type,
    brand_relevance,
    address_line_1,
    area,
    city,
    state,
    country,
    primary_contact_phone,
    website,
    latitude,
    longitude,
    current_lead_stage,
    is_active,
    created_by,
    updated_by
  )
  select
    i.name,
    i.normalized_name,
    i.institution_type,
    'both',
    nullif(i.address_line_1, ''),
    nullif(i.area, ''),
    nullif(i.city, ''),
    nullif(i.state, ''),
    'India',
    nullif(i.primary_contact_phone, ''),
    nullif(i.website, ''),
    i.latitude,
    i.longitude,
    'new_lead',
    true,
    null,
    null
  from incoming i
  where not exists (
    select 1
    from public.institutions p
    where p.normalized_name = i.normalized_name
      and p.institution_type = i.institution_type
  )
  returning 1
)

update public.institutions p
set
  name = coalesce(nullif(p.name, ''), i.name),
  address_line_1 = coalesce(nullif(p.address_line_1, ''), nullif(i.address_line_1, '')),
  area = coalesce(nullif(p.area, ''), nullif(i.area, '')),
  city = coalesce(nullif(p.city, ''), nullif(i.city, '')),
  state = coalesce(nullif(p.state, ''), nullif(i.state, '')),
  primary_contact_phone = coalesce(nullif(p.primary_contact_phone, ''), nullif(i.primary_contact_phone, '')),
  website = coalesce(nullif(p.website, ''), nullif(i.website, '')),
  latitude = coalesce(p.latitude, i.latitude),
  longitude = coalesce(p.longitude, i.longitude),
  is_active = true,
  updated_at = now()
from incoming i
where p.normalized_name = i.normalized_name
  and p.institution_type = i.institution_type;

-- Replacement behavior:
-- Mark old Hyderabad/Telangana School/College records inactive if they are not in the new file
-- and they are still in early pipeline states.
update public.institutions p
set
  is_active = false,
  updated_at = now()
where p.institution_type in ('School', 'College')
  and (coalesce(p.state, '') ilike 'telangana%' or coalesce(p.city, '') ilike '%hyderabad%')
  and p.current_lead_stage in ('new_lead', 'contacted', 'visited')
  and not exists (
    select 1
    from incoming i
    where i.normalized_name = p.normalized_name
      and i.institution_type = p.institution_type
  );

commit;
`;

fs.writeFileSync(outputPath, sql, "utf8");
console.log(`Generated ${outputPath}`);
console.log(`Input rows: ${rows.length}`);
console.log(`Imported rows: ${deduped.length}`);
